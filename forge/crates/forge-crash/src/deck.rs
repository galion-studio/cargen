//! Writer for the Radioss block-format input deck read by OpenCourant
//! (starter file `<name>_0000.rad`, engine file `<name>_0001.rad`).
//! Units: Mg, mm, s.

use crate::mesh::Mesh;
use crate::params::{TopBoundary, TubeCrush};
use std::fmt::Write;

pub const WALL_NODE_ID: u32 = 1;
const PART_TUBE: u32 = 1;
const GRN_BOTTOM: u32 = 1;
const GRN_TUBE: u32 = 3;
const GRN_WALL: u32 = 4;
const SURF_TUBE: u32 = 1;
const FN_RAMP: u32 = 1;
const FN_HARD: u32 = 2;

pub struct Deck {
    pub starter: String,
    pub engine: String,
}

/// Fixed-width real, 20 columns.
pub fn f20(x: f64) -> String {
    let s = if x == 0.0 {
        "0.0".to_string()
    } else if (1e-3..1e7).contains(&x.abs()) {
        let s = format!("{:.9}", x);
        let s = s.trim_end_matches('0');
        if s.ends_with('.') { format!("{s}0") } else { s.to_string() }
    } else {
        format!("{:.10e}", x)
    };
    assert!(s.len() <= 20, "real does not fit 20 columns: {s}");
    format!("{s:>20}")
}

pub fn i10(x: u32) -> String {
    format!("{x:>10}")
}

fn id_list(out: &mut String, ids: &[u32]) {
    for chunk in ids.chunks(10) {
        for id in chunk {
            out.push_str(&i10(*id));
        }
        out.push('\n');
    }
}

pub fn build(p: &TubeCrush, mesh: &Mesh, run_name: &str) -> Deck {
    let mut s = String::new();
    let t = p.thickness_mm;
    let hmin = mesh.actual_size_mm.0.min(mesh.actual_size_mm.1);
    let tend = p.end_time_s();

    // ---- header and control
    writeln!(s, "#RADIOSS STARTER\n# Generated by forge-crash (MIT). Case {}.\n# Units: Mg, mm, s (N, MPa, mJ)", p.case_id).unwrap();
    writeln!(s, "/BEGIN\n{run_name}\n      2026         0").unwrap();
    writeln!(s, "{:>20}{:>20}{:>20}", "Mg", "mm", "s").unwrap();
    writeln!(s, "{:>20}{:>20}{:>20}", "Mg", "mm", "s").unwrap();
    writeln!(s, "/TITLE\nForge P1a square tube axial crush {}", p.case_id).unwrap();

    // ---- material: tabulated elasto-plastic (LAW36), rate independent
    writeln!(s, "/MAT/PLAS_TAB/1\n{}", p.material.name).unwrap();
    writeln!(s, "#        Init. dens.\n{}", f20(p.material.density_t_per_mm3)).unwrap();
    writeln!(s, "#                  E                  Nu           Eps_p_max               Eps_t               Eps_m").unwrap();
    writeln!(s, "{}{}{}{}{}", f20(p.material.youngs_mpa), f20(p.material.poisson), f20(0.0), f20(0.0), f20(0.0)).unwrap();
    writeln!(s, "#  N_funct  F_smooth              C_hard               F_cut               Eps_f                  VP").unwrap();
    writeln!(s, "{}{}{}{}{}{:>10}{}", i10(1), i10(0), f20(0.0), f20(0.0), f20(0.0), "", i10(0)).unwrap();
    writeln!(s, "#  fct_IDp              Fscale   Fct_IDE                EInf                  CE").unwrap();
    writeln!(s, "{}{}{}{}{}", i10(0), f20(0.0), i10(0), f20(0.0), f20(0.0)).unwrap();
    writeln!(s, "# func_ID1\n{}", i10(FN_HARD)).unwrap();
    writeln!(s, "#           Fscale_1\n{}", f20(1.0)).unwrap();
    writeln!(s, "#          Eps_dot_1\n{}", f20(0.0)).unwrap();
    writeln!(s, "/FUNCT/{FN_HARD}\nhardening: plastic strain vs true stress (MPa)").unwrap();
    for (e, sig) in &p.material.hardening {
        writeln!(s, "{}{}", f20(*e), f20(*sig)).unwrap();
    }

    // ---- shell property: QEPH (Ishell=24), N integration points
    writeln!(s, "/PROP/SHELL/1\ntube wall t={t}").unwrap();
    writeln!(s, "#   Ishell    Ismstr     Ish3n    Idrill    Ipinch                  P_Thick_Fail").unwrap();
    writeln!(s, "{}{}{}{}{}{:>10}{}", i10(24), i10(0), i10(0), i10(0), i10(0), "", f20(0.0)).unwrap();
    writeln!(s, "#                 Hm                  Hf                  Hr                  Dm                  Dn").unwrap();
    writeln!(s, "{}{}{}{}{}", f20(0.0), f20(0.0), f20(0.0), f20(0.0), f20(0.0)).unwrap();
    writeln!(s, "#        N                         Thick              Ashear              Ithick     Iplas      Ipos").unwrap();
    writeln!(s, "{}{:>10}{}{}{:>10}{}{}{}", i10(p.integration_points), "", f20(t), f20(0.0), "", i10(1), i10(1), i10(0)).unwrap();

    writeln!(s, "/PART/{PART_TUBE}\ntube\n#  prop_ID    mat_ID\n{}{}", i10(1), i10(1)).unwrap();

    // ---- nodes (wall reference node first) and shells
    writeln!(s, "/NODE").unwrap();
    writeln!(s, "{}{}{}{}", i10(WALL_NODE_ID), f20(0.0), f20(0.0), f20(p.length_mm + 1.0e-3)).unwrap();
    for (id, x) in &mesh.nodes {
        writeln!(s, "{}{}{}{}", i10(*id), f20(x[0]), f20(x[1]), f20(x[2])).unwrap();
    }
    writeln!(s, "/SHELL/{PART_TUBE}").unwrap();
    for (id, n) in &mesh.quads {
        writeln!(s, "{}{}{}{}{}", i10(*id), i10(n[0]), i10(n[1]), i10(n[2]), i10(n[3])).unwrap();
    }

    // ---- groups
    writeln!(s, "/GRNOD/NODE/{GRN_BOTTOM}\nbottom ring").unwrap();
    id_list(&mut s, &mesh.bottom_nodes);
    writeln!(s, "/GRNOD/PART/{GRN_TUBE}\nall tube nodes\n{}", i10(PART_TUBE)).unwrap();
    writeln!(s, "/GRNOD/NODE/{GRN_WALL}\nwall node\n{}", i10(WALL_NODE_ID)).unwrap();
    writeln!(s, "/SURF/PART/{SURF_TUBE}\ntube surface\n{}", i10(PART_TUBE)).unwrap();

    // ---- bottom end clamped (specimen standing on the base block)
    writeln!(s, "/BCS/1\nbottom clamped\n#  Tra rot   skew_ID  grnod_ID\n   111 111{}{}", i10(0), i10(GRN_BOTTOM)).unwrap();

    // ---- moving rigid platen
    let slide = match p.top_boundary { TopBoundary::TiedWall => 1, TopBoundary::FrictionWall => 2 };
    writeln!(s, "/RWALL/PLANE/1\nplaten").unwrap();
    writeln!(s, "#  node_ID     Slide  grnd_ID1  grnd_ID2\n{}{}{}{}", i10(WALL_NODE_ID), i10(slide), i10(GRN_TUBE), i10(GRN_BOTTOM)).unwrap();
    if slide == 2 {
        writeln!(s, "#                  d                fric            Diameter                           ifq").unwrap();
        writeln!(s, "{}{}{}{:>20}{}", f20(0.0), f20(p.friction), f20(0.0), "", i10(0)).unwrap();
    } else {
        writeln!(s, "#                  d                fric            Diameter").unwrap();
        writeln!(s, "{}{:>20}{}", f20(0.0), "", f20(0.0)).unwrap();
    }
    writeln!(s, "#               Mass                 VX0                 VY0                 VZ0").unwrap();
    writeln!(s, "{}{}{}{}", f20(1.0e-3), f20(0.0), f20(0.0), f20(0.0)).unwrap();
    writeln!(s, "#                XM1                 YM1                 ZM1").unwrap();
    writeln!(s, "{}{}{}", f20(0.0), f20(0.0), f20(p.length_mm - 10.0)).unwrap();

    // platen velocity: linear ramp to 1 then constant, scaled by -v (moves -z)
    writeln!(s, "/FUNCT/{FN_RAMP}\nplaten speed ramp").unwrap();
    if p.ramp_time_s > 0.0 {
        writeln!(s, "{}{}", f20(0.0), f20(0.0)).unwrap();
        writeln!(s, "{}{}", f20(p.ramp_time_s), f20(1.0)).unwrap();
    } else {
        writeln!(s, "{}{}", f20(0.0), f20(1.0)).unwrap();
    }
    writeln!(s, "{}{}", f20(10.0 * tend), f20(1.0)).unwrap();
    writeln!(s, "/IMPVEL/1\nplaten velocity").unwrap();
    writeln!(s, "#funct_IDT       Dir   skew_ID sensor_ID  grnod_ID  frame_ID     Icoor").unwrap();
    writeln!(s, "{}{:>10}{}{}{}{}{}", i10(FN_RAMP), "Z", i10(0), i10(0), i10(GRN_WALL), i10(0), i10(0)).unwrap();
    writeln!(s, "#            Scale_x             Scale_y              Tstart               Tstop").unwrap();
    writeln!(s, "{}{}{}{}", f20(1.0), f20(-p.platen_speed_mm_s), f20(0.0), f20(0.0)).unwrap();

    // ---- self contact of the tube wall
    let gapmax = t.min(0.9 * hmin);
    writeln!(s, "/INTER/TYPE7/1\ntube self contact").unwrap();
    writeln!(s, "# grnod_id   surf_id      Istf      Ithe      Igap                Ibag      Idel     Icurv      Iadm").unwrap();
    writeln!(s, "{}{}{}{}{}{:>10}{}{}{}{}", i10(GRN_TUBE), i10(SURF_TUBE), i10(4), i10(0), i10(1), "", i10(0), i10(0), i10(0), i10(0)).unwrap();
    writeln!(s, "#          Fscalegap             Gap_max             Fpenmax                         Itied      Ists").unwrap();
    writeln!(s, "{}{}{}{:>20}{}{}", f20(0.0), f20(gapmax), f20(0.0), "", i10(0), i10(0)).unwrap();
    writeln!(s, "#              Stmin               Stmax   Percent_mesh_size               dtmin  Irem_gap   Irem_i2").unwrap();
    writeln!(s, "{}{}{}{}{}{}", f20(0.0), f20(0.0), f20(0.0), f20(0.0), i10(0), i10(0)).unwrap();
    writeln!(s, "#              Stfac                Fric              GAPmin              Tstart               Tstop").unwrap();
    writeln!(s, "{}{}{}{}{}", f20(1.0), f20(p.friction), f20(0.5 * gapmax), f20(0.0), f20(0.0)).unwrap();
    writeln!(s, "#      IBC                        Inacti               VIS_S               VIS_F              Bumult").unwrap();
    writeln!(s, "{:>7}000{:>20}{}{}{}{}", "", "", i10(6), f20(0.0), f20(0.0), f20(0.0)).unwrap();
    writeln!(s, "#    Ifric    Ifiltr               Xfreq     Iform   sens_ID   fct_IDF             AscaleF   fric_ID").unwrap();
    writeln!(s, "{}{}{}{}{}{}{}{}", i10(0), i10(0), f20(0.0), i10(0), i10(0), i10(0), f20(0.0), i10(0)).unwrap();

    // ---- time-history requests
    writeln!(s, "/TH/RWALL/1\nplaten force\n#var\nDEF\n#obj\n{}", i10(1)).unwrap();
    writeln!(s, "/TH/NODE/2\nplaten node\n#var\nDEF\n#  node_ID   Iskew\n{}{}", i10(WALL_NODE_ID), i10(0)).unwrap();
    writeln!(s, "/TH/PART/3\ntube energies\n#var\nDEF\n#obj\n{}", i10(PART_TUBE)).unwrap();
    writeln!(s, "/END").unwrap();

    // ---- engine
    let mut e = String::new();
    writeln!(e, "# Generated by forge-crash (MIT). Case {}.", p.case_id).unwrap();
    writeln!(e, "/RUN/{run_name}/1\n{}", f20(tend)).unwrap();
    writeln!(e, "/TFILE/4\n{}", f20(p.th_dt_s)).unwrap();
    let frames = p.anim_frames.max(1) as f64;
    writeln!(e, "/ANIM/DT\n{}{}", f20(0.0), f20(tend / frames * 0.999)).unwrap();
    writeln!(e, "/ANIM/ELEM/EPSP\n/ANIM/ELEM/THIC\n/ANIM/VECT/DISP").unwrap();
    writeln!(e, "/PRINT/-2000\n/PARITH/ON\n/MON/ON").unwrap();
    if p.dt_floor_fraction > 0.0 {
        // Selective nodal mass scaling: only nodes whose time step would fall below
        // dt_floor_fraction * (h_min / c) receive added mass. Reported as added-mass %.
        let c = (p.material.youngs_mpa / (p.material.density_t_per_mm3 * (1.0 - p.material.poisson.powi(2)))).sqrt();
        let dtmin = p.dt_floor_fraction * hmin / c;
        writeln!(e, "/DT/NODA/CST/0\n#             Tscale                Tmin\n{}{}", f20(0.9), f20(dtmin)).unwrap();
    }
    writeln!(e, "/END").unwrap();

    Deck { starter: s, engine: e }
}
