"""Graphs for the README validation section. Reads data/crush-theory-check.csv
(generated by scripts/crush_theory.py) and, when present, the P1a outputs.
Writes PNGs to forge/docs/img/ (or docs/img/ if forge/ is absent).
Never draws a simulated curve unless a real P1a result file exists."""
import csv, glob, json, os, statistics
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
IMG = os.path.join(ROOT, "forge", "docs", "img") if os.path.isdir(os.path.join(ROOT, "forge")) else os.path.join(ROOT, "docs", "img")
os.makedirs(IMG, exist_ok=True)
INK, GRID = "#1b1f24", "#d0d7de"
plt.rcParams.update({"figure.facecolor": "white", "axes.facecolor": "white", "axes.edgecolor": INK,
                     "axes.labelcolor": INK, "xtick.color": INK, "ytick.color": INK, "text.color": INK,
                     "font.size": 10.5, "axes.grid": True, "grid.color": GRID, "grid.linewidth": 0.6,
                     "axes.spines.top": False, "axes.spines.right": False, "savefig.dpi": 160})
SRC = {"park2022": ("Park et al. 2022 (data: Jung 1997), quasi-static", "#0969da", "o"),
       "aj1984": ("Abramowicz & Jones 1984", "#cf222e", "s"),
       "aj1986": ("Abramowicz & Jones 1986", "#8250df", "D"),
       "aljawi2002": ("Aljawi 2002, quasi-static", "#1a7f37", "^")}

def rows():
    with open(os.path.join(ROOT, "data", "crush-theory-check.csv")) as fh:
        return list(csv.DictReader(l for l in fh if not l.startswith("#")))

def caption(fig, text):
    fig.text(0.01, 0.01, text, fontsize=7.4, color="#57606a", ha="left", va="bottom")

def parity(R):
    fig, ax = plt.subplots(figsize=(7.6, 7.0))
    fig.subplots_adjust(bottom=0.23, top=0.9)
    hi = max(max(float(r["mean_force_kN"]), float(r["theory_CS6844_kN"])) for r in R) * 1.12
    lo = 8
    xs = np.geomspace(lo, hi, 50)
    ax.fill_between(xs, xs * 0.9, xs * 1.1, color="#afb8c1", alpha=0.35, lw=0, label="±10 % band")
    ax.plot(xs, xs, color=INK, lw=1)
    for key, (lab, col, mk) in SRC.items():
        sub = [r for r in R if r["source_key"] == key]
        for load, fill in (("quasi-static", True), ("dynamic", False)):
            s = [r for r in sub if r["loading"] == load]
            if not s:
                continue
            x = [float(r["theory_CS6844_kN"]) for r in s]
            y = [float(r["mean_force_kN"]) for r in s]
            ax.scatter(x, y, s=42, marker=mk, facecolor=col if fill else "white", edgecolor=col, lw=1.4,
                       label=f"{lab}" + ("" if key in ("park2022", "aljawi2002") else f", {load}"), zorder=3)
    ax.set_xscale("log"); ax.set_yscale("log")
    ax.set_xlim(lo, hi); ax.set_ylim(lo, hi)
    ax.set_xlabel("Predicted mean crushing force, closed-form theory [kN]")
    ax.set_ylabel("Measured mean crushing force [kN]")
    within = sum(abs(float(r["err_CS6844_pct"])) <= 10 for r in R)
    ax.set_title(f"Axial crush of thin-walled steel tubes: measured vs theory\n"
                 f"{len(R)} tests, {within} within ±10 %", fontsize=12, loc="left")
    ax.legend(loc="upper left", fontsize=8, frameon=False)
    caption(fig, "Data: Park, Cho & Kim 2022, Materials 15:2107 (Tables 1, 2, 4; tests by Jung 1997); Abramowicz & Jones 1984, IJIE 2:179 "
                 "(Tables 1-4);\nAbramowicz & Jones 1986, IJIE 4:243 (Tables 1, 3-6); Aljawi 2002, 6th Saudi Eng. Conf.\nTheory: A&J 1984 eq.33 / 1986 eq.19 "
                 "(square, symmetric), 1986 eq.22/23 (mode B / extensional),\n1986 eq.46 (circular); sigma0 = sigma_u; Cowper-Symonds D = 6844 1/s, p = 3.91 "
                 "(A&J eq.25).\nComputed by scripts/crush_theory.py. Log axes. Hollow = dynamic drop-hammer test.")
    p = os.path.join(IMG, "crush-parity.png"); fig.savefig(p); plt.close(fig); return p

def sea(R):
    groups, order = {}, []
    for r in R:
        c, t = float(r["c_mm"]), float(r["t_mm"])
        sec = "circular" if r["section"] == "circular" else "square"
        if r["source_key"] == "park2022":
            g = f'Park 2022 {r["id"].split("-")[1]}: square {c:.0f}x{t:.1f} mm'
        elif r["source_key"] == "aj1984":
            c, t = (37.07, 1.152) if c < 40 else (49.31, 1.63)
            g = f'A&J 1984: square {c:.1f}x{t:.2f} mm, {r["loading"]}'
        elif r["source_key"] == "aj1986":
            tid = r["id"].split("-")[1].rstrip("0123456789")
            g = f'A&J 1986 type {tid}: {sec}, {r["loading"]}'
        else:
            g = f'Aljawi 2002: square {c:.0f}x{t:.1f} mm, quasi-static'
        if g not in groups:
            groups[g] = []; order.append(g)
        groups[g].append(r)
    n = len(order)
    fig, ax = plt.subplots(figsize=(10.5, 0.36 * n + 2.4))
    fig.subplots_adjust(left=0.38, right=0.97, top=1 - 0.9 / (0.36 * n + 2.4), bottom=1.25 / (0.36 * n + 2.4))
    for i, g in enumerate(order):
        y = n - 1 - i
        vals = [float(r["SEA_kJ_kg"]) for r in groups[g]]
        r0 = groups[g][0]
        col = SRC[r0["source_key"]][1]
        dyn = r0["loading"] == "dynamic"
        ax.barh(y, statistics.mean(vals), color="white" if dyn else col, edgecolor=col, lw=1.5,
                hatch="///" if dyn else None, height=0.7)
        ax.scatter(vals, [y] * len(vals), color=INK, s=10, zorder=3)
        ax.text(max(vals) + 0.6, y, f"{statistics.mean(vals):.1f}  (n={len(vals)})", va="center", fontsize=8, color="#57606a")
    ax.set_yticks(range(n), list(reversed(order)), fontsize=8.5)
    ax.grid(axis="y", visible=False)
    ax.set_xlabel("Specific energy absorption, SEA [kJ/kg]  (energy per crushed mass)")
    ax.set_title("SEA of published steel-tube crush tests\nbar = mean, dots = individual tests, hatched = dynamic drop-hammer", fontsize=11.5, loc="left")
    ax.set_xlim(0, max(float(r["SEA_kJ_kg"]) for r in R) * 1.18)
    caption(fig, "SEA = measured mean force / (rho x wall cross-section area), computed by scripts/crush_theory.py from published mean force and geometry; rho = 7850 kg/m3 assumed\n"
                 "where the paper gives none (all except Aljawi 2002). Sources: Park, Cho & Kim 2022 (Materials 15:2107); Abramowicz & Jones 1984 (IJIE 2:179) and 1986 (IJIE 4:243);\n"
                 "Aljawi 2002. A&J 1986 types A and B are short, thick (c/t 7-9) tubes in the extensional mode. These are published tests, not Forge simulations.")
    p = os.path.join(IMG, "crush-sea.png"); fig.savefig(p); plt.close(fig); return p

def p1a():
    """Simulated vs experimental curves, only from real P1a outputs."""
    exp_csv = os.path.join(ROOT, "forge", "data", "p1a", "park2022_us2_fig3_digitized.csv")
    sim = None
    for cand in sorted(glob.glob(os.path.join(ROOT, "forge", "docs", "physics", "*.json")) +
                       glob.glob(os.path.join(ROOT, "forge", "results", "**", "*.json"), recursive=True) +
                       glob.glob(os.path.join(ROOT, "forge", "runs", "p1a*", "*.json"))):
        try:
            j = json.load(open(cand))
        except Exception:
            continue
        curve = j.get("force_displacement") or j.get("sim_curve") or j.get("curve")
        if curve:
            sim = (cand, curve)
            break
    d, F = [], []
    with open(exp_csv) as fh:
        for l in fh:
            if l[0].isdigit():
                a, b = l.split(",")[:2]; d.append(float(a)); F.append(float(b))
    d, F = np.array(d), np.array(F)
    E = np.concatenate([[0], np.cumsum(0.5 * (F[1:] + F[:-1]) * np.diff(d))]) / 1e3  # kN*mm = J -> kJ
    fig, (a1, a2) = plt.subplots(1, 2, figsize=(12.5, 5.0))
    fig.subplots_adjust(bottom=0.24, top=0.86, wspace=0.22, left=0.06, right=0.99)
    a1.plot(d, F, color="#0969da", lw=1.4, label="Experiment US-2 (digitized Fig. 3)")
    a1.axhline(101.0, color="#0969da", ls="--", lw=0.9, label="Experiment Pm = 101.0 kN (Table 4)")
    a2.plot(d, E, color="#0969da", lw=1.6, label="Experiment US-2 (integrated digitized curve)")
    status = "pending"
    if sim:
        status = "sim"
        sd = np.array([p[0] for p in sim[1]]); sf = np.array([p[1] for p in sim[1]])
        a1.plot(sd, sf, color="#cf222e", lw=1.4, label=f"OpenCourant P1a ({os.path.basename(sim[0])})")
        se = np.concatenate([[0], np.cumsum(0.5 * (sf[1:] + sf[:-1]) * np.diff(sd))]) / 1e3
        a2.plot(sd, se, color="#cf222e", lw=1.6, label="OpenCourant P1a")
    else:
        for ax in (a1, a2):
            ax.text(0.5, 0.55, "SIMULATION PENDING\nP1a OpenCourant run not finished;\nno simulated curve is shown",
                    transform=ax.transAxes, ha="center", va="center", fontsize=12, color="#9a6700",
                    bbox=dict(boxstyle="round,pad=0.6", fc="#fff8c5", ec="#d4a72c"))
    a1.set_xlabel("Axial displacement [mm]"); a1.set_ylabel("Axial force [kN]")
    a2.set_xlabel("Axial displacement [mm]"); a2.set_ylabel("Energy absorbed [kJ]")
    a1.set_title("P1a: force vs displacement, 100×100×2.8 mm A500 tube", fontsize=11.5, loc="left")
    a2.set_title("P1a: energy absorbed vs displacement", fontsize=11.5, loc="left")
    for ax in (a1, a2):
        ax.legend(loc="upper left", fontsize=8, frameon=False)
    caption(fig, "Experiment: Park, Cho & Kim 2022, Materials 15:2107, CC BY 4.0, specimen US-2 (tests by Jung 1997), quasi-static 0.05 mm/s. Curve digitized from Fig. 3 by "
                 "forge/scripts/digitize_park2022_fig3.py\n(about ±1 mm, ±2 kN; initial spike under-resolved, Table 4 peak = 337.1 kN). Energy = trapezoidal integral of the digitized curve. "
                 + ("Simulation: OpenCourant run, file named in legend." if sim else "Simulation: none yet (pending)."))
    p = os.path.join(IMG, "p1a-force-energy.png"); fig.savefig(p); plt.close(fig); return p, status

if __name__ == "__main__":
    R = rows()
    print(parity(R)); print(sea(R)); print(p1a())
