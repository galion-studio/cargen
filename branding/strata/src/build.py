"""Strata brand concept for cargen: builds every SVG master (deterministic, seeded).
Run from branding/strata/:  python src/build.py && src/render.sh"""
import os, sys
import numpy as np
sys.path.insert(0, os.path.dirname(__file__))
from palette import C
from fontpath import text_path, metrics

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REPO = os.path.dirname(os.path.dirname(ROOT))
HDR = "<!-- SPDX-License-Identifier: MIT. Copyright (c) 2026 galion-studio. Original artwork, generated by branding/strata/src/build.py. Text is outlined (Archivo / IBM Plex, SIL OFL 1.1). -->"
SEED_BANNER, SEED_SOCIAL = 1983, 2022   # fixed seeds: Wierzbicki & Abramowicz 1983; Park et al. 2022

def f(v): return f"{v:.2f}".rstrip("0").rstrip(".")
def write(rel, w, h, body, title="cargen"):
    p = os.path.join(ROOT, rel); os.makedirs(os.path.dirname(p), exist_ok=True)
    open(p, "w").write(f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {f(w)} {f(h)}" width="{f(w)}" height="{f(h)}" role="img" aria-label="{title}"><title>{title}</title>\n{HDR}\n{body}</svg>\n')
    return p

# ---------------------------------------------------------------- mark geometry
# 64-unit grid. Three strata (paper / orange / paper) run flat, are thrust up through a
# steep kink band, then relax. The orange layer is the simulation inside the test corridor.
MARK = dict(V=64, rx=14, ts=(8, 10, 8), gap=4.5, x0=26, x1=33, rise=14, fall=7, top=21.5)
SMALL = dict(V=16, rx=3.5, ts=(2, 3, 2), gap=1, x0=6, x1=8, rise=4, fall=0, top=6)  # pixel-snapped flats

def band_polys(m, bleed=2.0):
    V = m["V"]; y = m["top"]; out = []
    for t in m["ts"]:
        pts = [(-bleed, y), (m["x0"], y), (m["x1"], y - m["rise"]), (V + bleed, y - m["rise"] + m["fall"] * (V + bleed - m["x1"]) / (V - m["x1"]))]
        poly = pts + [(x, yy + t) for x, yy in reversed(pts)]
        out.append("M" + " L".join(f"{f(x)},{f(yy)}" for x, yy in poly) + " Z")
        y += t + m["gap"]
    return out

def mark_group(m, tile, outer, mid, x=0, y=0, size=None, uid="m", tile_on=True, knockout=False):
    """Return an SVG <g> drawing the mark at (x,y) with edge length size."""
    V = m["V"]; k = (size or V) / V
    bands = band_polys(m, bleed=2.0 if tile_on else 0.0)
    g = f'<g transform="translate({f(x)} {f(y)}) scale({f(k)})">'
    if tile_on:
        g += f'<defs><clipPath id="{uid}c"><rect width="{V}" height="{V}" rx="{m["rx"]}"/></clipPath>'
        if knockout:
            g += f'<mask id="{uid}k"><rect width="{V}" height="{V}" fill="#fff"/>' + "".join(f'<path d="{d}" fill="#000"/>' for d in bands) + "</mask>"
        g += "</defs>"
        if knockout:
            return g + f'<rect width="{V}" height="{V}" rx="{m["rx"]}" fill="{tile}" mask="url(#{uid}k)"/></g>'
        g += f'<rect width="{V}" height="{V}" rx="{m["rx"]}" fill="{tile}"/><g clip-path="url(#{uid}c)">'
        g += "".join(f'<path d="{d}" fill="{c}"/>' for d, c in zip(bands, (outer, mid, outer))) + "</g></g>"
        return g
    return g + "".join(f'<path d="{d}" fill="{c}"/>' for d, c in zip(bands, (outer, mid, outer))) + "</g>"

# ---------------------------------------------------------------- wordmark
WM = dict(wdth=125, wght=700)
TRACK = -0.012
def wordmark(x, baseline, xh, color):
    """'cargen' in Archivo Expanded Bold; sized by x-height."""
    size = xh / (metrics("archivo", 100, **WM)["x"] / 100)
    d, w = text_path("cargen", "archivo", size, x, baseline, tracking=TRACK, **WM)
    return f'<path d="{d}" fill="{color}"/>', w, text_path.last_bounds

def lockup_group(x, y, h, theme, uid):
    """Horizontal lockup. The wordmark's x-height spans exactly the mark's left
    strata (top of upper band to bottom of orange band): letters sit in the rock."""
    m = MARK; k = h / 64
    top = y + m["top"] * k
    base = y + (m["top"] + m["ts"][0] + m["gap"] + m["ts"][1]) * k
    tile = C["graphite"]
    g = mark_group(m, tile, C["limestone"], C["fold"], x, y, h, uid)
    ink = C["limestone"] if theme == "dark" else C["graphite"]
    p, w, b = wordmark(x + h * 1.24, base, base - top, ink)
    return g + p, h * 1.24 + w, b

def stacked_group(cx, y, h, theme, uid):
    k = h / 64; ink = C["limestone"] if theme == "dark" else C["graphite"]
    g = mark_group(MARK, C["graphite"], C["limestone"], C["fold"], cx - h / 2, y, h, uid)
    xh = 22.5 * k * 0.62
    p, w, b = wordmark(0, 0, xh, ink)
    p2, w, b = wordmark(cx - w / 2 - b[0] / 2, y + h * 1.42, xh, ink)
    return g + p2, b

# ---------------------------------------------------------------- generative strata field (seeded)
def kink_field(W, H, seed, xk, rise, kw, fall, tilt, theme, y0=-60, y1=None, fade=None):
    """Sedimentary layers (seeded thicknesses and gentle undulation) cut by one inclined
    kink band, the same deformation as the mark. Returns SVG body."""
    rng = np.random.default_rng(seed)
    y1 = H + 80 if y1 is None else y1
    ys = [y0]
    while ys[-1] < y1:
        ys.append(ys[-1] + float(np.clip(rng.lognormal(np.log(13), 0.45), 5, 36)))
    ph = rng.uniform(0, 2 * np.pi, 3); lam = (rng.uniform(380, 520), rng.uniform(170, 240), rng.uniform(900, 1300))
    def boundary(yb, j):
        xs = xk + tilt * (yb - H / 2)
        xa = np.unique(np.concatenate([np.arange(-40, W + 41, 4.0), [xs, xs + kw]]))
        u = np.clip((xa - xs) / kw, 0, 1)
        d = rise * u - fall * np.maximum(xa - xs - kw, 0) / max(W - xs - kw, 1)
        und = 2.2 * np.sin(2 * np.pi * xa / lam[0] + ph[0] + j * 0.05) + 1.1 * np.sin(2 * np.pi * xa / lam[1] + ph[1] + j * 0.11) \
            + 5 * np.sin(2 * np.pi * xa / lam[2] + ph[2])
        return xa, yb - d + und
    B = [boundary(yb, j) for j, yb in enumerate(ys)]
    dark = theme == "dark"
    fills = (C["basalt"], "#161D25") if dark else (C["limestone"], "#E8E1D4")
    line = "#36414D" if dark else "#CFC5B5"
    line2 = "#5E6B79" if dark else "#A39886"
    body = ""
    for j in range(len(B) - 1):
        (xa, ya), (xb, yb) = B[j], B[j + 1]
        if j % 2:
            pts = " ".join(f"{f(x)},{f(y)}" for x, y in zip(xa, ya)) + " " + " ".join(f"{f(x)},{f(y)}" for x, y in zip(xb[::-1], yb[::-1]))
            body += f'<polygon points="{pts}" fill="{fills[1]}"/>'
    for j, (xa, ya) in enumerate(B):
        heavy = rng.random() < 0.18
        body += f'<polyline points="{" ".join(f"{f(x)},{f(y)}" for x, y in zip(xa, ya))}" fill="none" stroke="{line2 if heavy else line}" stroke-width="{1.8 if heavy else 1}" stroke-linejoin="miter"/>'
    if fade:
        a, b = fade
        body = (f'<defs><linearGradient id="fd" x1="{a[0]}" y1="{a[1]}" x2="{b[0]}" y2="{b[1]}" gradientUnits="userSpaceOnUse"><stop offset="0" stop-color="#fff" stop-opacity="0"/>'
                f'<stop offset="1" stop-color="#fff"/></linearGradient><mask id="fm"><rect x="-50" y="-50" width="{W + 100}" height="{H + 100}" fill="url(#fd)"/></mask></defs>'
                f'<g mask="url(#fm)">{body}</g>')
    return body

def fold_record_field(W, H, seed, x0, x1, base, kpx, theme):
    """Strata draped under a real crash record: the top boundary is the digitized axial
    crush force of Park et al. 2022 specimen US-2 (no values altered); deeper layers are
    progressively smoothed copies, seeded thicknesses."""
    a = np.loadtxt(os.path.join(REPO, "forge/data/p1a/park2022_us2_fig3_digitized.csv"), delimiter=",", skiprows=3, usecols=(0, 1))
    d, F = a[:, 0], a[:, 1]
    xs = x0 + d / d.max() * (x1 - x0)
    xg = np.arange(-20, W + 21, 2.0)
    Fg = np.interp(xg, xs, F, left=0, right=F[-1])
    rng = np.random.default_rng(seed)
    dark = theme == "dark"
    fills = (C["basalt"], "#161D25") if dark else (C["limestone"], "#E8E1D4")
    line = "#36414D" if dark else "#CFC5B5"
    curves, off = [], 0.0
    for j in range(60):
        win = 1 + int(j * 5)
        sm = np.convolve(np.pad(Fg, win, mode="edge"), np.ones(2 * win + 1) / (2 * win + 1), mode="same")[win:-win]
        cur = base - sm * kpx + off
        if curves: cur = np.maximum(cur, curves[-1] + 3.0)  # layers never cross
        curves.append(cur)
        off += float(np.clip(rng.lognormal(np.log(10), 0.4), 4, 26))
        if base - sm.max() * kpx + off > H + 30: break
    body = ""
    for j in range(len(curves) - 1):
        if j % 2 == 0:
            pts = " ".join(f"{f(x)},{f(y)}" for x, y in zip(xg, curves[j])) + " " + " ".join(f"{f(x)},{f(y)}" for x, y in zip(xg[::-1], curves[j + 1][::-1]))
            body += f'<polygon points="{pts}" fill="{fills[1]}"/>'
    for j, y in enumerate(curves[1:], 1):
        body += f'<polyline points="{" ".join(f"{f(x)},{f(v)}" for x, v in zip(xg, y))}" fill="none" stroke="{line}" stroke-width="1"/>'
    top = curves[0]
    # the record itself: measured test = blue (colour rule), never orange
    sel = (xg >= x0) & (xg <= x1)
    body += f'<polyline points="{" ".join(f"{f(x)},{f(v)}" for x, v in zip(xg[sel], top[sel]))}" fill="none" stroke="{C["ice"] if dark else C["glacier"]}" stroke-width="2" stroke-linejoin="round"/>'
    # cut as a specimen section: clean vertical faces at both ends
    edge = "#4A5562" if dark else "#B9AE9C"
    yl, yr = float(np.interp(x0, xg, top)), float(np.interp(x1, xg, top))
    faces = f'<path d="M{f(x0)},{f(yl)} V{H} M{f(x1)},{f(yr)} V{H}" stroke="{edge}" stroke-width="1.5" fill="none"/>'
    return f'<defs><clipPath id="sec"><rect x="{f(x0)}" y="0" width="{f(x1 - x0)}" height="{H}"/></clipPath></defs><g clip-path="url(#sec)">{body}</g>{faces}'

def mono(text, x, y, size, color, anchor="start", med=False):
    d, w = text_path(text, "plexmono-med" if med else "plexmono", size, x, y, anchor=anchor)
    return f'<path d="{d}" fill="{color}"/>', w

def sans(text, x, y, size, color, wght=400, anchor="start"):
    d, w = text_path(text, "plexsans", size, x, y, anchor=anchor, wght=wght)
    return f'<path d="{d}" fill="{color}"/>', w

def slot(x, y, w, h, theme, text="TAGLINE SLOT: EMPTY, OWNER CHOOSES (template only, do not publish)"):
    col = C["fold"] if theme == "dark" else C["oxide"]
    lab, _ = mono(text, x + 10, y + h / 2 + 4, 11, col)
    return f'<rect x="{f(x)}" y="{f(y)}" width="{f(w)}" height="{f(h)}" fill="none" stroke="{col}" stroke-width="1.5" stroke-dasharray="6 5"/>' + lab

# ---------------------------------------------------------------- assets
def build():
    out = []
    M = MARK
    # marks
    out.append(write("mark/cargen-strata-mark.svg", 64, 64, mark_group(M, C["graphite"], C["limestone"], C["fold"], uid="a"), "cargen mark"))
    out.append(write("mark/cargen-strata-mark-small.svg", 16, 16, mark_group(SMALL, C["graphite"], C["limestone"], C["fold"], uid="s"), "cargen mark, 16 px master"))
    out.append(write("mark/cargen-strata-mark-mono-graphite.svg", 64, 64, mark_group(M, C["graphite"], "", "", uid="k", knockout=True), "cargen mark, one colour"))
    out.append(write("mark/cargen-strata-mark-mono-limestone.svg", 64, 64, mark_group(M, C["limestone"], "", "", uid="k", knockout=True), "cargen mark, one colour reversed"))
    # glyph without tile (bands only), cut square at the ends
    gw = lambda o, mcol: mark_group(M, "", o, mcol, 0, 0, 64, "g", tile_on=False)
    out.append(write("mark/cargen-strata-glyph-on-light.svg", 64, 64, gw(C["graphite"], C["fold"]), "cargen glyph"))
    out.append(write("mark/cargen-strata-glyph-on-dark.svg", 64, 64, gw(C["limestone"], C["fold"]), "cargen glyph"))

    # wordmark (crop to the ink bounds + small margin)
    for theme, ink in (("dark", C["limestone"]), ("light", C["graphite"])):
        p, w, b = wordmark(0, 0, 100, ink)
        pad = 12
        body = f'<g transform="translate({f(pad - b[0])} {f(pad - b[1])})">{p}</g>'
        out.append(write(f"wordmark/cargen-wordmark-{theme}.svg", b[2] - b[0] + 2 * pad, b[3] - b[1] + 2 * pad, body, "cargen"))

    # lockups (transparent backgrounds; dark = for dark grounds)
    for theme in ("dark", "light"):
        h = 128; pad = 32
        g, w, b = lockup_group(pad, pad, h, theme, "l")
        bottom = max(pad + h, b[3])
        out.append(write(f"lockup/cargen-lockup-{theme}.svg", pad + w + pad + 4, bottom + pad, g, "cargen"))
        g2, b2 = stacked_group(200, pad, 128, theme, "t")
        out.append(write(f"lockup/cargen-lockup-stacked-{theme}.svg", 400, b2[3] + pad, g2, "cargen"))

    # banners 1280x320
    for theme in ("dark", "light"):
        bg = C["basalt"] if theme == "dark" else C["limestone"]
        field = kink_field(1280, 320, SEED_BANNER, xk=840, rise=100, kw=110, fall=40, tilt=0.6, theme=theme, y0=-40, y1=480, fade=((400, 0), (700, 0)))
        lk, w, b = lockup_group(96, 96, 128, theme, "b")
        for tmpl in (False, True):
            body = f'<rect width="1280" height="320" fill="{bg}"/>' + field + lk
            if tmpl:
                body += slot(96 + 128 * 1.24, 244, 520, 40, theme)
            name = f"banner/templates/cargen-banner-{theme}-tagline-slot-1280x320.svg" if tmpl else f"banner/cargen-banner-{theme}-1280x320.svg"
            out.append(write(name, 1280, 320, body, "cargen banner" + (" template" if tmpl else "")))

    # social preview 1280x640 (dark and light)
    for theme in ("dark", "light"):
        bg = C["basalt"] if theme == "dark" else C["limestone"]
        sec = C["ash"] if theme == "dark" else C["stone"]
        field = fold_record_field(1280, 640, SEED_SOCIAL, x0=80, x1=1200, base=548, kpx=0.7, theme=theme)
        lk, w, b = lockup_group(80, 72, 152, theme, "x")
        t1, _ = mono("galion-studio/cargen", 80 + 152 * 1.24 + 4, 72 + 152 + 34, 20, sec)
        c1, _ = mono("FOLD RECORD  axial crush force vs displacement, A500 tube US-2", 1200, 300, 12.5, sec, "end")
        c2, _ = mono("Park, Cho & Kim 2022, Materials 15:2107, CC BY 4.0, digitized Fig. 3", 1200, 320, 12.5, sec, "end")
        for tmpl in (False, True):
            body = f'<rect width="1280" height="640" fill="{bg}"/>' + field + lk + t1 + c1 + c2
            if tmpl:
                body += slot(80 + 152 * 1.24, 72 + 152 + 54, 360, 36, theme, "TAGLINE SLOT: EMPTY (template only)")
            name = f"social/templates/cargen-social-{theme}-tagline-slot-1280x640.svg" if tmpl else f"social/cargen-social-preview-{theme}-1280x640.svg"
            out.append(write(name, 1280, 640, body, "cargen social preview" + (" template" if tmpl else "")))
    return out

if __name__ == "__main__":
    for p in build(): print(os.path.relpath(p, ROOT))
