"""Earthrise palette, WCAG 2.x contrast table (palette/contrast.md) and swatch sheet (palette/palette.svg)."""
import os
from fontpath import text_path
OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "palette")
os.makedirs(OUT, exist_ok=True)
PAL = [  # name, hex, role
 ("Deep Space", "#060F1D", "night-sky top, deepest background"),
 ("Space Navy", "#0B1A2E", "primary dark: tiles, dark UI, text on light"),
 ("Horizon Navy", "#12304A", "night-sky horizon, cards on dark"),
 ("Aurora Green", "#3DDC97", "primary accent on dark: atmosphere arc, highlights"),
 ("Aurora Teal", "#1FB5A8", "secondary accent on dark, graph series"),
 ("Deep Teal", "#0E7C74", "accent and links on light backgrounds"),
 ("Sunrise Amber", "#F5A524", "the sun: one small accent per layout"),
 ("Ember", "#B4560F", "amber for text/lines on light (AA)"),
 ("Star White", "#F4F7FB", "primary light: text on dark, light backgrounds"),
 ("Mist", "#9FB3C8", "secondary text on dark"),
 ("Slate", "#4A5D73", "secondary text on light"),
]
def lum(h):
    c = [int(h[i:i+2], 16) / 255 for i in (1, 3, 5)]
    c = [x / 12.92 if x <= 0.04045 else ((x + 0.055) / 1.055) ** 2.4 for x in c]
    return 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2]
def cr(a, b):
    la, lb = sorted((lum(a), lum(b)), reverse=True)
    return (la + 0.05) / (lb + 0.05)
BGS = [("Space Navy", "#0B1A2E"), ("Deep Space", "#060F1D"), ("Horizon Navy", "#12304A"), ("Star White", "#F4F7FB"), ("White", "#FFFFFF")]
def grade(r):
    return "AAA" if r >= 7 else "AA" if r >= 4.5 else "AA large / UI" if r >= 3 else "below 3:1, not for text"
lines = ["<!-- SPDX-License-Identifier: MIT -->", "# Earthrise palette: WCAG 2.x contrast", "",
         "Generated by `src/palette.py` (relative-luminance formula from WCAG 2.1). AA = 4.5:1 body text, 3:1 large text (>= 24 px, or 18.7 px bold) and UI/graphics.", "",
         "| Colour | Hex | Role | " + " | ".join(f"vs {n} {h}" for n, h in BGS) + " |",
         "|---|---|---|" + "---|" * len(BGS)]
for n, h, role in PAL:
    lines.append(f"| {n} | `{h}` | {role} | " + " | ".join(f"{cr(h, b):.2f} {grade(cr(h, b))}" for _, b in BGS) + " |")
lines += ["", "## Approved text pairs (all pass AA for body text)", ""]
pairs = [("Star White", "Space Navy"), ("Mist", "Space Navy"), ("Aurora Green", "Space Navy"), ("Aurora Teal", "Deep Space"), ("Sunrise Amber", "Space Navy"),
         ("Space Navy", "Star White"), ("Slate", "Star White"), ("Deep Teal", "Star White"), ("Ember", "White"), ("Star White", "Horizon Navy")]
H = {n: h for n, h, _ in PAL}; H["White"] = "#FFFFFF"
for f, b in pairs:
    r = cr(H[f], H[b]); lines.append(f"- {f} `{H[f]}` on {b} `{H[b]}`: **{r:.2f}:1** {grade(r)}")
    assert r >= 4.5, (f, b, r)
lines += ["", "## Never for text", "- Aurora Green, Aurora Teal or Sunrise Amber on Star White/white (below 3:1; use Deep Teal or Ember instead).",
          "- Deep Teal or Ember on any navy for small text (below 4.5:1)."]
open(os.path.join(OUT, "contrast.md"), "w").write("\n".join(lines) + "\n")
# swatch sheet
W, rowh = 1280, 0
cells = []
x0, y0, cw, ch, gap = 69, 120, 214, 230, 18
for i, (n, h, role) in enumerate(PAL):
    col, row = i % 5, i // 5
    x, y = x0 + col * (cw + gap), y0 + row * (ch + gap)
    dark = lum(h) < 0.2
    fg = "#F4F7FB" if dark else "#0B1A2E"
    cells.append(f'<rect x="{x}" y="{y}" width="{cw}" height="{ch}" rx="18" fill="{h}" stroke="#0B1A2E" stroke-opacity=".12"/>')
    d, _ = text_path(n, "inter", 19, x + 18, y + ch - 62, wght=600); cells.append(f'<path d="{d}" fill="{fg}"/>')
    d, _ = text_path(h, "plexmono", 16, x + 18, y + ch - 38); cells.append(f'<path d="{d}" fill="{fg}" opacity=".85"/>')
    best = max(BGS[:1] + BGS[3:4], key=lambda bg: cr(h, bg[1]))
    lab = f"{cr(h, '#0B1A2E'):.1f} navy  {cr(h, '#F4F7FB'):.1f} white"
    d, _ = text_path(lab, "plexmono", 12.5, x + 18, y + ch - 17); cells.append(f'<path d="{d}" fill="{fg}" opacity=".7"/>')
Ht = y0 + 3 * (ch + gap) + 30
d, _ = text_path("Earthrise palette", "sora", 34, 69, 72, wght=430); hdr = f'<path d="{d}" fill="#0B1A2E"/>'
d, _ = text_path("contrast ratios vs Space Navy and Star White (WCAG 2.x). Details: palette/contrast.md", "inter", 15, 69, 100, wght=400); hdr += f'<path d="{d}" fill="#4A5D73"/>'
# proportion bar: how much of each colour a typical layout uses
bar = [("#0B1A2E", .52), ("#12304A", .14), ("#F4F7FB", .2), ("#1FB5A8", .06), ("#3DDC97", .05), ("#F5A524", .03)]
bx, by, bw = x0 + 2 * (cw + gap), y0 + 2 * (ch + gap), 3 * cw + 2 * gap
cx = bx
for c, f in bar:
    cells.append(f'<rect x="{cx:.1f}" y="{by+40}" width="{bw*f:.1f}" height="70" fill="{c}"/>'); cx += bw * f
cells.append(f'<rect x="{bx}" y="{by+40}" width="{bw}" height="70" fill="none" stroke="#0B1A2E" stroke-opacity=".15"/>')
d, _ = text_path("Typical proportion: mostly navy and white, aurora as a thin line, one amber sun", "inter", 14, bx, by + 26, wght=500); cells.append(f'<path d="{d}" fill="#4A5D73"/>')
svg = (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {Ht}" width="{W}" height="{Ht}" role="img" aria-label="Earthrise palette">'
       f'<title>Earthrise palette</title><!-- SPDX-License-Identifier: MIT. Text outlined from Sora, Inter, IBM Plex Mono (SIL OFL 1.1). -->'
       f'<rect width="{W}" height="{Ht}" fill="#FFFFFF"/>{hdr}{"".join(cells)}</svg>')
open(os.path.join(OUT, "palette.svg"), "w").write(svg)
print(open(os.path.join(OUT, "contrast.md")).read())
