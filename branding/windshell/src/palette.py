"""Wind & Shell palette: WCAG 2.1 contrast table (palette/contrast.md) + swatch sheet (palette/palette.svg/.png)."""
import os, subprocess, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from glyphs import text_path

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "palette"); os.makedirs(OUT, exist_ok=True)
PAL = [  # name, hex, role
    ("Graphite", "#16202A", "primary dark: ground, tiles, text on light (existing cargen code)"),
    ("Shell Graphite", "#24323F", "raised tile on dark, shell region inside the stagnation streamline"),
    ("Paper", "#F4F1EA", "primary light: ground, mark body, text on dark"),
    ("Sand", "#E9DFCB", "shell region and corridor fill on light; never text"),
    ("Signal Orange", "#F26B1D", "crush cap; validated-simulation line; one accent per layout (existing cargen code)"),
    ("Orange Ink", "#B5470C", "orange for text and thin lines on light"),
    ("Wind Blue", "#2F5F8F", "streamlines, corridor edges and measured test data on light"),
    ("Sky", "#7FA8D6", "streamlines, corridor edges and measured test data on dark"),
    ("Ink Grey", "#5A6470", "secondary text on light; unvalidated estimates (dashed)"),
    ("Mist", "#9AA3AD", "secondary text on dark; unvalidated estimates on dark (dashed)"),
]
H = {n: h for n, h, _ in PAL}; H["White"] = "#FFFFFF"

def lum(h):
    c = [int(h[i:i + 2], 16) / 255 for i in (1, 3, 5)]
    c = [x / 12.92 if x <= 0.04045 else ((x + 0.055) / 1.055) ** 2.4 for x in c]
    return 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2]

def cr(a, b):
    la, lb = sorted((lum(a), lum(b)), reverse=True)
    return (la + 0.05) / (lb + 0.05)

def grade(r):
    return "AAA" if r >= 7 else "AA" if r >= 4.5 else "AA large / UI" if r >= 3 else "fail (decor only)"

BGS = ["Graphite", "Shell Graphite", "Paper", "White"]
L = ["<!-- SPDX-License-Identifier: MIT -->", "# Wind & Shell palette: WCAG 2.1 contrast", "",
     "Generated by `src/palette.py` (WCAG 2.1 relative luminance). AA = 4.5:1 for body text; 3:1 for large text "
     "(24 px+, or 18.7 px+ bold) and for UI parts and graph lines.", "",
     "| Colour | Hex | Role | " + " | ".join(f"on {b} `{H[b]}`" for b in BGS) + " |",
     "|---|---|---|" + "---|" * len(BGS)]
for n, h, role in PAL:
    L.append(f"| {n} | `{h}` | {role} | " + " | ".join(f"{cr(h, H[b]):.2f} {grade(cr(h, H[b]))}" for b in BGS) + " |")
PAIRS = [("Paper", "Graphite"), ("Paper", "Shell Graphite"), ("Signal Orange", "Graphite"), ("Sky", "Graphite"), ("Sky", "Shell Graphite"),
         ("Mist", "Graphite"), ("Mist", "Shell Graphite"), ("Graphite", "Paper"), ("Graphite", "Sand"), ("Wind Blue", "Paper"),
         ("Orange Ink", "Paper"), ("Ink Grey", "Paper"), ("Orange Ink", "White"), ("Wind Blue", "White")]
L += ["", "## Approved text pairs (each passes AA for body text; checked by assert)", ""]
for f, b in PAIRS:
    r = cr(H[f], H[b]); assert r >= 4.5, (f, b, r)
    L.append(f"- {f} `{H[f]}` on {b} `{H[b]}`: **{r:.2f}:1** {grade(r)}")
L += ["", "## Graphics only (3:1 UI/graph minimum)", ""]
for f, b in (("Signal Orange", "Shell Graphite"), ("Signal Orange", "White"), ("Orange Ink", "Graphite")):
    r = cr(H[f], H[b]); assert r >= 3, (f, b, r)
    L.append(f"- {f} on {b}: {r:.2f}:1, fine for marks, lines and large text, not for small text")
L += ["", "## Never", "- Signal Orange for small text or thin lines on Paper/white (2.7:1). Use Orange Ink.",
      "- Sky or Mist as text on Paper/white. Wind Blue or Ink Grey as text on Graphite.",
      "- Sand as text anywhere; it is a surface colour.", "",
      "## Colour carries meaning on graphs",
      "Signal Orange / Orange Ink = cargen simulation or model; Wind Blue / Sky (and Graphite) = physical test data; "
      "Ink Grey / Mist dashed = unvalidated estimate. Never draw an unvalidated number in orange."]
open(os.path.join(OUT, "contrast.md"), "w").write("\n".join(L) + "\n")

# swatch sheet 1280 x 720
W, Hh = 1280, 720
o = [f'<rect width="{W}" height="{Hh}" fill="#F4F1EA"/>']
d, _ = text_path("Wind & Shell palette", name="plexsans", wght=600, size=30, x=64, y=84); o.append(f'<path d="{d}" fill="#16202A"/>')
d, _ = text_path("contrast ratios vs Graphite / Paper (WCAG 2.1)", name="plexmono", size=15, x=64, y=114); o.append(f'<path d="{d}" fill="#5A6470"/>')
cw, ch, gap, x0, y0 = 214, 250, 18, 64, 150
for i, (n, h, role) in enumerate(PAL):
    col, row = i % 5, i // 5
    x, y = x0 + col * (cw + gap), y0 + row * (ch + gap)
    fg = "#F4F1EA" if lum(h) < 0.18 else "#16202A"
    o.append(f'<rect x="{x}" y="{y}" width="{cw}" height="{ch}" rx="16" fill="{h}" stroke="#16202A" stroke-opacity="0.12"/>')
    for txt, font, size, dy, op in ((n, "plexsans", 20, ch - 74, 1), (h, "plexmono", 16, ch - 48, 0.9),
                                    (f"{cr(h, H['Graphite']):.1f} G   {cr(h, H['Paper']):.1f} P", "plexmono", 13, ch - 22, 0.75)):
        d, _ = text_path(txt, name=font, wght=600 if font == "plexsans" else 500, size=size, x=x + 18, y=y + dy)
        o.append(f'<path d="{d}" fill="{fg}" opacity="{op}"/>')
p = os.path.join(OUT, "palette.svg")
open(p, "w").write(f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {Hh}" width="{W}" height="{Hh}" role="img" aria-label="Wind and Shell palette">'
                   "<!-- SPDX-License-Identifier: MIT. Text outlined from IBM Plex (SIL OFL 1.1). -->" + "".join(o) + "</svg>\n")
subprocess.run(["rsvg-convert", p, "-o", os.path.join(OUT, "palette.png")], check=True)
print(os.path.join(OUT, "contrast.md")); print(os.path.join(OUT, "palette.png"))
