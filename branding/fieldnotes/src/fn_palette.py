from fn_lib import *

ROLES = [  # key, name, role, text-safe on
    ("graphite", "Graphite", "existing cargen charcoal: dark ground, text on paper"),
    ("paper", "Field Paper", "light ground: plates, docs, social"),
    ("chalk", "Chalk", "text and line work on graphite"),
    ("sepia", "Sepia", "secondary text on paper: captions, provenance"),
    ("dust", "Dust", "secondary text on graphite"),
    ("signal", "Signal Orange", "existing cargen orange: the car; validated simulation on graphite"),
    ("signalInk", "Signal Ink", "signal orange for text, thin lines, simulation curves on paper"),
    ("cyan", "Cyanotype", "physical test data on paper"),
    ("cyanPale", "Cyanotype Pale", "physical test data on graphite"),
    ("fern", "Fern", "the leaf on paper; never data"),
    ("lichen", "Lichen", "the leaf on graphite; never data"),
    ("sage", "Sage", "leaf wash, fills only"),
    ("vellum", "Vellum", "panels and caption blocks on paper (non-text)"),
    ("rule", "Rule", "grid / graticule on graphite (non-text)"),
]
GROUNDS = [("graphite", "Graphite"), ("paper", "Field Paper"), ("white", "White")]

def lum(h):
    h = h.lstrip("#"); c = [int(h[i:i + 2], 16) / 255 for i in (0, 2, 4)]
    c = [x / 12.92 if x <= 0.04045 else ((x + 0.055) / 1.055) ** 2.4 for x in c]
    return 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2]

def ratio(a, b):
    la, lb = lum(a), lum(b)
    return (max(la, lb) + 0.05) / (min(la, lb) + 0.05)

def grade(r):
    return "AAA" if r >= 7 else "AA" if r >= 4.5 else "AA large / UI" if r >= 3 else "fail"

def hexof(k):
    return "#FFFFFF" if k == "white" else P[k]

def contrast_md():
    L = ["<!-- SPDX-License-Identifier: MIT -->", "# Field Notes palette: WCAG 2.1 contrast", "",
         "Generated by `src/fn_palette.py` (WCAG 2.1 relative-luminance formula). AA = 4.5:1 for body text, "
         "3:1 for large text (>= 24 px, or 18.7 px bold) and for UI / graphics.", "",
         "| Colour | Hex | Role | on Graphite #16202A | on Field Paper #F3EDDF | on White #FFFFFF |", "|---|---|---|---|---|---|"]
    for k, name, role in ROLES:
        cells = []
        for g, _ in GROUNDS:
            if g == k:
                cells.append("(same)"); continue
            r = ratio(P[k], hexof(g)); cells.append(f"{r:.2f} {grade(r)}")
        L.append(f"| {name} | `{P[k]}` | {role} | " + " | ".join(cells) + " |")
    L += ["", "## Approved text pairs (all pass AA for body text)", ""]
    pairs = [("chalk", "graphite"), ("dust", "graphite"), ("signal", "graphite"), ("cyanPale", "graphite"), ("lichen", "graphite"),
             ("graphite", "paper"), ("sepia", "paper"), ("signalInk", "paper"), ("cyan", "paper"), ("fern", "paper"),
             ("graphite", "white"), ("signalInk", "white"), ("cyan", "white")]
    for a, b in pairs:
        r = ratio(P[a], hexof(b))
        nb = dict(GROUNDS)[b]
        L.append(f"- {dict((k, n) for k, n, _ in ROLES)[a]} `{P[a]}` on {nb} `{hexof(b)}`: **{r:.2f}:1** {grade(r)}")
    L += ["", "## Never for text",
          "- Signal Orange on Field Paper or white (2.6:1 / 3.0:1): use Signal Ink `#A8461A` instead. Signal Orange stays for the car body, the mark, and fills.",
          "- Cyanotype, Signal Ink, Fern or Sepia on Graphite (below 3:1): use Cyanotype Pale, Signal Orange, Lichen or Dust.",
          "- Cyanotype Pale, Lichen, Sage, Dust on paper or white (below 2.5:1).",
          "- Vellum and Rule are surfaces and hairlines, never text.",
          "", "## Colour meaning in figures",
          "- Cyanotype = physical test. Signal = validated simulation. Sepia / Dust, dotted or dashed = unvalidated or pending.",
          "- Fern / Lichen belong to the leaf only; they never encode data."]
    return "\n".join(L) + "\n"

def sheet():
    W, H = 1280, 700
    b = f'<rect width="{W}" height="{H}" fill="{P["paper"]}"/>'
    t, _ = T("Field Notes palette", "serif-semi", 30, 48, 64, P["graphite"]); b += t
    t, _ = T("WCAG 2.1 ratios vs graphite / paper. Full table: palette/contrast.md", "mono", 13, 48, 90, P["sepia"]); b += t
    cols = 7; sw, sh, gx = 158, 140, 12
    for i, (k, name, role) in enumerate(ROLES):
        x = 48 + (i % cols) * (sw + gx); y = 120 + (i // cols) * (sh + 90)
        stroke = f' stroke="{P["graphite"]}" stroke-opacity="0.25"' if k in ("paper", "vellum", "chalk") else ""
        b += f'<rect x="{x}" y="{y}" width="{sw}" height="{sh}" fill="{P[k]}"{stroke}/>'
        # Aa sample in the best text pair on this swatch
        on_dark = ratio(P[k], P["chalk"]) > ratio(P[k], P["graphite"])
        tc = P["chalk"] if on_dark else P["graphite"]
        t, _ = T("Aa", "serif-semi", 26, x + 12, y + 38, tc); b += t
        t, _ = T(name, "sans-semi", 14, x, y + sh + 22, P["graphite"]); b += t
        t, _ = T(P[k], "mono", 12.5, x, y + sh + 40, P["sepia"]); b += t
        rg = ratio(P[k], P["graphite"]); rp = ratio(P[k], P["paper"])
        t, _ = T(f"G {rg:4.1f}  P {rp:4.1f}", "mono", 12, x, y + sh + 58, P["sepia"]); b += t
    # meaning key
    y = 642
    for i, (k, lab, dash) in enumerate((("cyan", "physical test", None), ("signalInk", "validated simulation", None),
                                        ("sepia", "unvalidated / pending", "2 4"), ("fern", "the leaf only, never data", None))):
        x = 48 + i * 300
        da = f' stroke-dasharray="{dash}"' if dash else ""
        b += f'<path d="M{x} {y-5} h36" stroke="{P[k]}" stroke-width="3"{da}/>'
        t, _ = T(lab, "mono", 13, x + 46, y, P["graphite"]); b += t
    return svg(W, H, b, "cargen Field Notes palette")

if __name__ == "__main__":
    write("palette/palette.svg", sheet())
    write("palette/contrast.md", contrast_md())
